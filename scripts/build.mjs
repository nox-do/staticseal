import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const [app, format, wrapper, svg, preview] = await Promise.all([
  read('src/app.html'), read('src/format.mjs'), read('src/wrapper.mjs'), read('src/seal.svg'), read('src/preview.mjs')
]);
const logoModule = '// Generated by scripts/build.mjs from src/seal.svg.\nexport const sealLogo = ' + JSON.stringify(svg.trim()) + ';\n';
const inline = source => source.replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const replace = (source, marker, value) => {
  if (source.split(marker).length !== 2) throw new Error('Expected exactly one marker: ' + marker);
  return source.replace(marker, () => value);
};
let html = replace(app, '<!-- STATICSEAL_LOGO -->', svg.trim());
html = replace(html, '/* STATICSEAL_FORMAT */', inline(format) + '\n' + inline(preview));
html = replace(html, '/* STATICSEAL_WRAPPER */', "const sealLogo = document.getElementById('seal-logo').outerHTML;\n" + inline(wrapper));
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by npm run build. Edit src/app.html and src/*.mjs instead. -->');
for (const [path, content] of [['src/logo.mjs', logoModule], ['index.html', html]]) {
  if (process.argv.includes('--check')) {
    if (await read(path).catch(() => '') !== content) throw new Error(path + ' is stale; run npm run build.');
  } else {
    await writeFile(new URL(path, root), content);
  }
}
console.log(process.argv.includes('--check') ? 'Generated files are current.' : 'Built standalone index.html and logo module.');
