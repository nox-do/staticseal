import { readFile, writeFile } from 'node:fs/promises';
import CleanCSS from 'clean-css';
import { minify as minifyJs } from 'terser';
import { minify as minifyHtml } from 'html-minifier-terser';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const [
  app,
  format,
  wrapper,
  svg,
  preview,
  wrapperCss,
  wrapperHtml,
  reader,
  gzip,
  compression,
  cryptoHelper,
  viewer,
  limits,
  creation
] = await Promise.all(
  [
    'src/app.html',
    'src/format.mjs',
    'src/wrapper.mjs',
    'src/seal.svg',
    'src/preview.mjs',
    'src/wrapper.css',
    'src/wrapper.html',
    'src/reader.js',
    'src/gzip.mjs',
    'src/compression.mjs',
    'src/crypto.mjs',
    'src/viewer.mjs',
    'src/limits.mjs',
    'src/creation.mjs'
  ].map(read)
);
const [collection, htmlImport, srcset, selectionUi, website] = await Promise.all(
  ['src/collection.mjs', 'src/html-import.mjs', 'src/srcset-parser.mjs', 'src/multi-file-ui.js', 'src/website.mjs'].map(
    read
  )
);
const [base64, cssReferences] = await Promise.all(['src/base64.mjs', 'src/css-references.mjs'].map(read));
const srcsetLicense = (await read('third-party/srcset-parser.LICENSE.txt')).trim().replace(/\s+/g, ' ');
const minifyCss = css => {
  const result = new CleanCSS({ level: 0, inline: false, rebase: false }).minify(css);
  if (result.errors.length || result.warnings.length) {
    throw new Error('CSS minification failed: ' + [...result.errors, ...result.warnings].join('\n'));
  }
  return result.styles;
};
// Keep function scopes intact: createFormat/createPreview are serialized with toString().
// No test-specific names or hooks are preserved. Property names are never mangled.
const compactJs = async (source, module = false, sequences = true) =>
  (
    await minifyJs(source, {
      module,
      compress: {
        defaults: false,
        booleans: true,
        conditionals: true,
        dead_code: true,
        unused: true,
        evaluate: true,
        if_return: true,
        join_vars: true,
        loops: true,
        properties: true,
        sequences
      },
      mangle: true,
      format: { comments: false, inline_script: true }
    })
  ).code;
const htmlOptions = {
  collapseWhitespace: true,
  conservativeCollapse: true,
  removeComments: true,
  minifyCSS: false,
  minifyJS: false
};
// Source imports can span multiple lines after formatting.
const inline = source => source.replace(/^import\s[\s\S]*?;\r?\n/gm, '').replace(/^export /gm, '');
const replace = (source, marker, value) => {
  if (source.split(marker).length !== 2) throw new Error('Expected exactly one marker: ' + marker);
  return source.replace(marker, () => value);
};
const logo = svg.trim().replace(/>\s+</g, '><');
const scriptString = value => JSON.stringify(value).replaceAll('<', '\\u003c');
const logoModule =
  '// Generated by scripts/build.mjs from src/seal.svg.\nexport const sealLogo = ' + JSON.stringify(logo) + ';\n';
// Keep the optional restore statement separate so raw envelopes omit it entirely.
const readerTemplate = await compactJs(reader, false, false);
for (const marker of ['STATICSEAL_FORMAT', 'STATICSEAL_VIEWER', 'STATICSEAL_RESTORE', 'STATICSEAL_DECODER']) {
  if (readerTemplate.split(marker).length !== 2) throw new Error('Expected one reader marker: ' + marker);
}
if (!/STATICSEAL_RESTORE\(([$\w]+)\);/.test(readerTemplate)) throw new Error('Missing standalone reader restore call.');
const [openingCss, viewerCss, textCss, markdownCss, notesCss, codeCss, responsiveCss] = wrapperCss.split(
  /\/\* (?:VIEWER|TEXT|MARKDOWN|NOTES|CODE|RESPONSIVE) \*\//
);
const wrapperTemplate = (await minifyHtml(wrapperHtml, htmlOptions)).trim();
const templatesModule =
  '// Generated by scripts/build.mjs from src/wrapper.html, src/wrapper.css and src/reader.js.\n' +
  'export const openingStyles = ' +
  scriptString(minifyCss(openingCss)) +
  ';\n' +
  'export const viewerStyles = ' +
  scriptString(minifyCss(viewerCss + responsiveCss)) +
  ';\n' +
  'export const previewStyles = ' +
  JSON.stringify([textCss, markdownCss, notesCss, codeCss].map(minifyCss)) +
  ';\n' +
  'export const wrapperTemplate = ' +
  scriptString(wrapperTemplate) +
  ';\n' +
  'export const readerTemplate = ' +
  scriptString(readerTemplate) +
  ';\n';
const factoriesModule =
  '// Generated by scripts/build.mjs from src/format.mjs, src/preview.mjs, src/gzip.mjs, src/crypto.mjs, src/viewer.mjs, src/collection.mjs and src/website.mjs.\n' +
  (await compactJs(
    format +
      '\n' +
      preview +
      '\n' +
      gzip +
      '\n' +
      cryptoHelper +
      '\n' +
      viewer +
      '\n' +
      collection.slice(collection.indexOf('export function createCollectionReader()')) +
      '\n' +
      website,
    true
  )) +
  '\n';
async function buildApp() {
  let html = replace(app, '/* STATICSEAL_SELECTION_UI */', selectionUi);
  html = replace(html, '<!-- STATICSEAL_LOGO -->', logo);
  html = replace(html, '/* STATICSEAL_BROWSER_LIMITS */', inline(limits));
  html = html.replace(/<style>([\s\S]*?)<\/style>/, (_, css) => '<style>' + minifyCss(css) + '</style>');
  html = replace(
    html,
    '/* STATICSEAL_FORMAT */',
    inline(base64) +
      '\n' +
      inline(format) +
      '\n' +
      inline(preview) +
      '\n' +
      inline(gzip) +
      '\n' +
      inline(compression) +
      '\n' +
      inline(creation) +
      '\n' +
      inline(cryptoHelper) +
      '\n' +
      inline(viewer) +
      '\n' +
      inline(collection) +
      '\n' +
      srcset
        .replace(/export\s*\{[^}]*\};?/, '')
        .replace(/\bprocess\b/g, 'parseSrcset')
        .replace(/\bserialize\b/g, 'serializeSrcset') +
      '\n' +
      inline(website) +
      '\n' +
      inline(cssReferences) +
      '\n' +
      inline(htmlImport)
  );
  html = replace(
    html,
    '/* STATICSEAL_WRAPPER */',
    "const sealLogo = document.getElementById('seal-logo').outerHTML;\n" +
      inline(templatesModule) +
      '\n' +
      inline(wrapper)
  );
  const script = html.match(/<script>([\s\S]*?)<\/script>/);
  if (!script) throw new Error('Missing app script.');
  html = replace(html, script[0], '<script>' + (await compactJs(script[1])) + '</script>');
  html = (await minifyHtml(html, htmlOptions)).trim() + '\n';
  html = html.replace('<script>', () => '<script>' + '/*! ' + srcsetLicense + ' */');
  return html;
}
const html = await buildApp();
for (const [path, content] of [
  ['src/logo.mjs', logoModule],
  ['src/wrapper-template.mjs', templatesModule],
  ['src/reader-factories.mjs', factoriesModule],
  ['index.html', html]
]) {
  if (process.argv.includes('--check')) {
    if ((await read(path).catch(() => '')) !== content) throw new Error(path + ' is stale; run npm run build.');
  } else {
    await writeFile(new URL(path, root), content);
  }
}
console.log(
  process.argv.includes('--check')
    ? 'Generated files are current.'
    : 'Built compact standalone app and wrapper modules.'
);
