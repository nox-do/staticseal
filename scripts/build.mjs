import { readFile, writeFile } from 'node:fs/promises';
import CleanCSS from 'clean-css';
import { minify as minifyJs } from 'terser';
import { minify as minifyHtml } from 'html-minifier-terser';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const [
  app,
  format,
  wrapper,
  svg,
  preview,
  wrapperCss,
  wrapperHtml,
  reader,
  gzip,
  compression,
  cryptoHelper,
  viewer,
  browserLimits,
  creation
] = await Promise.all(
  [
    'src/app.html',
    'src/format.mjs',
    'src/wrapper.mjs',
    'src/seal.svg',
    'src/preview.mjs',
    'src/wrapper.css',
    'src/wrapper.html',
    'src/reader.js',
    'src/gzip.mjs',
    'src/compression.mjs',
    'src/crypto.mjs',
    'src/viewer.mjs',
    'src/browser-limits.mjs',
    'src/creation.mjs'
  ].map(read)
);
const [collection, htmlImport, srcset, extendedUi] = await Promise.all(
  ['src/collection.mjs', 'src/html-import.mjs', 'src/srcset-parser.mjs', 'src/multi-file-ui.js'].map(read)
);
const minifyCss = css => {
  const result = new CleanCSS({ level: 0, inline: false, rebase: false }).minify(css);
  if (result.errors.length || result.warnings.length) {
    throw new Error('CSS minification failed: ' + [...result.errors, ...result.warnings].join('\n'));
  }
  return result.styles;
};
// Keep function scopes intact: createFormat/createPreview are serialized with toString().
// No test-specific names or hooks are preserved. Property names are never mangled.
const compactJs = async (source, module = false, sequences = true) =>
  (
    await minifyJs(source, {
      module,
      compress: {
        defaults: false,
        booleans: true,
        conditionals: true,
        dead_code: true,
        evaluate: true,
        if_return: true,
        join_vars: true,
        loops: true,
        properties: true,
        sequences
      },
      mangle: true,
      format: { comments: false, inline_script: true }
    })
  ).code;
const htmlOptions = {
  collapseWhitespace: true,
  conservativeCollapse: true,
  removeComments: true,
  minifyCSS: false,
  minifyJS: false
};
// Source imports can span multiple lines after formatting.
const inline = source => source.replace(/^import\s[\s\S]*?;\r?\n/gm, '').replace(/^export /gm, '');
const replace = (source, marker, value) => {
  if (source.split(marker).length !== 2) throw new Error('Expected exactly one marker: ' + marker);
  return source.replace(marker, () => value);
};
const logo = svg.trim().replace(/>\s+</g, '><');
const scriptString = value => JSON.stringify(value).replaceAll('<', '\\u003c');
const logoModule =
  '// Generated by scripts/build.mjs from src/seal.svg.\nexport const sealLogo = ' + JSON.stringify(logo) + ';\n';
// Keep the optional restore statement separate so raw envelopes omit it entirely.
const readerTemplate = await compactJs(reader, false, false);
for (const marker of ['STATICSEAL_FORMAT', 'STATICSEAL_VIEWER', 'STATICSEAL_RESTORE', 'STATICSEAL_DECODER']) {
  if (readerTemplate.split(marker).length !== 2) throw new Error('Expected one reader marker: ' + marker);
}
if (!/STATICSEAL_RESTORE\(([$\w]+)\);/.test(readerTemplate)) throw new Error('Missing standalone reader restore call.');
const wrapperTemplate = await minifyHtml(replace(wrapperHtml, 'STATICSEAL_STYLES', minifyCss(wrapperCss)), htmlOptions);
const templatesModule =
  '// Generated by scripts/build.mjs from src/wrapper.html, src/wrapper.css and src/reader.js.\n' +
  'export const wrapperTemplate = ' +
  scriptString(wrapperTemplate) +
  ';\n' +
  'export const readerTemplate = ' +
  scriptString(readerTemplate) +
  ';\n';
const factoriesModule =
  '// Generated by scripts/build.mjs from src/format.mjs, src/preview.mjs, src/gzip.mjs, src/crypto.mjs, src/viewer.mjs and src/collection.mjs.\n' +
  (await compactJs(
    format +
      '\n' +
      preview +
      '\n' +
      gzip +
      '\n' +
      cryptoHelper +
      '\n' +
      viewer +
      '\n' +
      collection.slice(collection.indexOf('export function createCollection()')),
    true
  )) +
  '\n';
async function buildApp(extended) {
  let html = app;
  const extras =
    '<label class="folder-picker">Choose a folder<input id="source-folder" type="file" webkitdirectory multiple></label>' +
    '<p class="meta">Choose files directly, or open a folder and select it with its contents. Selections are added to the list. Everything stays on this device.</p>' +
    '<ul id="selection-list" class="selection-list"></ul><p id="selection-report" class="meta" role="status" style="white-space:pre-line"></p>' +
    '<button id="download-prepared" type="button" hidden>Download prepared HTML</button>';
  html = replace(html, '<!-- STATICSEAL_EXTRA_PICKER -->', extended ? extras : '');
  html = replace(html, '/* STATICSEAL_EXTENDED_INIT */', extended ? extendedUi : '');
  html = replace(
    html,
    '/* STATICSEAL_EXTENDED_CHANGE */',
    extended ? 'return selectFiles(Array.from(sourceFile.files));' : ''
  );
  html = replace(html, '/* STATICSEAL_EXTENDED_SUBMIT */', extended ? 'await sealSelection(); return;' : '');
  if (extended) {
    html = html.replace(
      'id="source-file" name="source-file" type="file"',
      'id="source-file" name="source-file" type="file" multiple'
    );
    html = html
      .replaceAll('Choose your file', 'Choose files')
      .replaceAll('Seal a file', 'Seal files')
      .replace('One file in.', 'Files in.');
    html = html.replace('<title>', '<title>FatSeal experiment · ');
    html = html
      .replace('<div class="brand mobile-brand">staticseal</div>', '<div class="brand mobile-brand">fatseal</div>')
      .replace('<span class="brand">staticseal</span>', '<span class="brand">fatseal</span>')
      .replace(
        'Package a document or self-contained webpage into a single HTML file.',
        'Package selected files or an HTML page with its resources into a single HTML file.'
      )
      .replace('Pick a file to share', 'Pick files to share')
      .replace(
        'For self-contained HTML files. Shows the original layout and runs included JavaScript.',
        'Selected resources are embedded into the recognized HTML entry. Other files stay separate. Included JavaScript runs after opening.'
      );
    html = html.replace(
      '</style>',
      '.folder-picker{position:relative;display:inline-flex;justify-self:start;align-items:center;padding:8px 12px;min-height:40px;border:1px solid #ccd9d5;border-radius:8px;cursor:pointer}.folder-picker:focus-within{outline:3px solid #27665d40;outline-offset:3px}#selection-list:empty,#selection-report:empty{display:none}.selection-list{padding-left:20px;max-height:240px;overflow:auto}.selection-list li{overflow-wrap:anywhere;margin:6px 0}.selection-list button{min-height:30px;padding:3px 9px;margin-left:4px}[hidden]{display:none!important}</style>'
    );
  }
  html = replace(html, '<!-- STATICSEAL_LOGO -->', logo);
  html = replace(html, '/* STATICSEAL_BROWSER_LIMITS */', inline(browserLimits));
  html = html.replace(/<style>([\s\S]*?)<\/style>/, (_, css) => '<style>' + minifyCss(css) + '</style>');
  html = replace(
    html,
    '/* STATICSEAL_FORMAT */',
    inline(format) +
      '\n' +
      inline(preview) +
      '\n' +
      inline(gzip) +
      '\n' +
      inline(compression) +
      '\n' +
      inline(creation) +
      '\n' +
      inline(cryptoHelper) +
      '\n' +
      inline(viewer) +
      (extended
        ? '\n' +
          inline(collection) +
          '\n' +
          srcset
            .replace(/export\s*\{[^}]*\};?/, '')
            .replace(/\bprocess\b/g, 'parseSrcset')
            .replace(/\bserialize\b/g, 'serializeSrcset') +
          '\n' +
          inline(htmlImport)
        : '')
  );
  html = replace(
    html,
    '/* STATICSEAL_WRAPPER */',
    "const sealLogo = document.getElementById('seal-logo').outerHTML;\n" +
      inline(templatesModule) +
      '\n' +
      inline(wrapper)
  );
  const script = html.match(/<script>([\s\S]*?)<\/script>/);
  if (!script) throw new Error('Missing app script.');
  html = replace(html, script[0], '<script>' + (await compactJs(script[1])) + '</script>');
  html = (await minifyHtml(html, htmlOptions)).trim() + '\n';
  if (extended) html = html.replace('<script>', () => '<script>' + srcset.slice(0, srcset.indexOf('export {')));
  return html;
}
const html = await buildApp(false);
const fatHtml = await buildApp(true);
for (const [path, content] of [
  ['src/logo.mjs', logoModule],
  ['src/wrapper-template.mjs', templatesModule],
  ['src/reader-factories.mjs', factoriesModule],
  ['index.html', html],
  ['fatseal.html', fatHtml]
]) {
  if (process.argv.includes('--check')) {
    if ((await read(path).catch(() => '')) !== content) throw new Error(path + ' is stale; run npm run build.');
  } else {
    await writeFile(new URL(path, root), content);
  }
}
console.log(
  process.argv.includes('--check')
    ? 'Generated files are current.'
    : 'Built compact standalone app and wrapper modules.'
);
