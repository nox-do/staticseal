import { readFile, writeFile } from 'node:fs/promises';
import CleanCSS from 'clean-css';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const [app, format, wrapper, svg, preview, wrapperCss] = await Promise.all([
  read('src/app.html'), read('src/format.mjs'), read('src/wrapper.mjs'), read('src/seal.svg'), read('src/preview.mjs'), read('src/wrapper.css')
]);
// Only compact CSS syntax; keep values, selectors and rule order unchanged.
const minifyCss = css => {
  const result = new CleanCSS({ level: 0, inline: false, rebase: false }).minify(css);
  if (result.errors.length || result.warnings.length) {
    throw new Error('CSS minification failed: ' + [...result.errors, ...result.warnings].join('\n'));
  }
  return result.styles;
};
const wrapperStyles = minifyCss(wrapperCss);
const stylesModule = '// Generated by scripts/build.mjs from src/wrapper.css.\nexport const wrapperStyles = ' + JSON.stringify(wrapperStyles) + ';\n';
const logoModule = '// Generated by scripts/build.mjs from src/seal.svg.\nexport const sealLogo = ' + JSON.stringify(svg.trim()) + ';\n';
const inline = source => source.replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const replace = (source, marker, value) => {
  if (source.split(marker).length !== 2) throw new Error('Expected exactly one marker: ' + marker);
  return source.replace(marker, () => value);
};
let html = replace(app, '<!-- STATICSEAL_LOGO -->', svg.trim());
html = html.replace(/<style>([\s\S]*?)<\/style>/, (_, css) => '<style>' + minifyCss(css) + '</style>');
html = replace(html, '/* STATICSEAL_FORMAT */', inline(format) + '\n' + inline(preview));
html = replace(html, '/* STATICSEAL_WRAPPER */', "const sealLogo = document.getElementById('seal-logo').outerHTML;\nconst wrapperStyles = " + JSON.stringify(wrapperStyles) + ';\n' + inline(wrapper));
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by npm run build. Edit src/app.html and src/*.mjs instead. -->');
for (const [path, content] of [['src/logo.mjs', logoModule], ['src/wrapper-styles.mjs', stylesModule], ['index.html', html]]) {
  if (process.argv.includes('--check')) {
    if (await read(path).catch(() => '') !== content) throw new Error(path + ' is stale; run npm run build.');
  } else {
    await writeFile(new URL(path, root), content);
  }
}
console.log(process.argv.includes('--check') ? 'Generated files are current.' : 'Built standalone index.html, logo and wrapper styles.');
